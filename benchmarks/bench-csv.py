#!/usr/bin/env python3
"""Competitive benchmark: `qwc --validate-csv` vs `zsv check --parser fast`.

Reproduces benchmarks/README.md Finding 18. For each corpus shape it times both
tools (best-of-N wall clock, warm page cache) and prints the speedup. The
corpora are generated by gen-csv.py on first run if missing.

  # build the Release binary first, then:
  cmake --build build --target qwc
  python3 benchmarks/bench-csv.py                 # all shapes, default sizes
  python3 benchmarks/bench-csv.py --runs 11 --size 268435456
  python3 benchmarks/bench-csv.py --qwc ./build/qwc --zsv zsv

Both tools answer the same question (constant column count per row); zsv's
`--parser fast` is its branchless SIMD engine, so this is SIMD-vs-SIMD with the
extra variable being qwc's cross-core parallelism.
"""
import argparse
import os
import shutil
import statistics
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "test-data")
SHAPES = ["unquoted", "sprinkled", "heavy", "ragged"]
DN = subprocess.DEVNULL


def ensure_corpus(shape, size, seed):
    path = os.path.join(DATA, f"csv-{shape}.csv")
    if not os.path.exists(path):
        print(f"generating {path} ...", file=sys.stderr)
        subprocess.run(
            [sys.executable, os.path.join(HERE, "gen-csv.py"),
             "--shape", shape, "--size", str(size), "--seed", str(seed)],
            check=True,
        )
    return path


def bench(cmd, runs):
    subprocess.run(cmd, stdout=DN, stderr=DN)  # warm the cache / discard output
    ts = []
    for _ in range(runs):
        t0 = time.perf_counter()
        subprocess.run(cmd, stdout=DN, stderr=DN)
        ts.append(time.perf_counter() - t0)
    return min(ts), statistics.median(ts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--qwc", default=os.path.join(os.getcwd(), "build", "qwc"))
    ap.add_argument("--zsv", default="zsv")
    ap.add_argument("--runs", type=int, default=7)
    ap.add_argument("--size", type=int, default=256 * 1024 * 1024)
    ap.add_argument("--seed", type=int, default=1234)
    args = ap.parse_args()

    if not (os.path.isfile(args.qwc) and os.access(args.qwc, os.X_OK)):
        sys.exit(f"qwc not found/executable at {args.qwc} "
                 f"(build it: cmake --build build --target qwc)")
    if shutil.which(args.zsv) is None:
        sys.exit(f"zsv not found on PATH ({args.zsv}); install it "
                 f"(e.g. brew install zsv) or pass --zsv")

    def qwc_cmd(path, *flags):
        return [args.qwc, "--validate-csv", *flags, path]

    def zsv_cmd(path):
        return [args.zsv, "check", "--parser", "fast", path]

    print(f"qwc={args.qwc}  zsv={args.zsv}  runs={args.runs}  "
          f"size={args.size}  (median wall-clock)\n")
    header = f"{'corpus':12} {'qwc':>12} {'zsv':>12} {'speedup':>9}"
    print(header)
    print("-" * len(header))
    for shape in SHAPES:
        path = ensure_corpus(shape, args.size, args.seed)
        flags = ("--fast",) if shape == "ragged" else ()
        _, q = bench(qwc_cmd(path, *flags), args.runs)
        _, z = bench(zsv_cmd(path), args.runs)
        label = "ragged --fast" if shape == "ragged" else shape
        print(f"{label:12} {q * 1000:9.1f} ms {z * 1000:9.1f} ms "
              f"{z / q:8.2f}x")

    # The default-mode (row-listing) cost on the ragged corpus, for contrast.
    ragged = os.path.join(DATA, "csv-ragged.csv")
    _, qd = bench(qwc_cmd(ragged, "--first"), args.runs)
    print(f"\nragged --first (full inspection re-scan): {qd * 1000:.1f} ms "
          f"(vs --fast above; --fast skips the re-scan)")


if __name__ == "__main__":
    main()
