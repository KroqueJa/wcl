#!/usr/bin/env python3
"""Competitive benchmark: `qwc --validate-csv` vs `zsv check --parser fast`.

Two sections. The first reproduces benchmarks/README.md Finding 18 (the four
classic shapes, qwc on its fast path). The second is the default-mode
enumeration contest the TODO targets: on a file with many scattered ragged
rows, qwc's default --all/--first must re-read and serially re-scan to name the
rows (the "inspection tax"), so it can LOSE to single-threaded `zsv check` even
though --fast wins handily. Each cell is best-of-N wall clock, warm page cache.
Corpora are generated by gen-csv.py on first run if missing.

  # build the Release binary first, then:
  cmake --build build --target qwc -DQWC_BUILD_TESTS=OFF   # (or with tests)
  python3 benchmarks/bench-csv.py                 # all shapes, default sizes
  python3 benchmarks/bench-csv.py --runs 11 --size 268435456
  python3 benchmarks/bench-csv.py --qwc ./build/qwc --zsv zsv
  python3 benchmarks/bench-csv.py --size 681574400 --ragged-density 50  # ~650MB

Both tools answer the same question (constant column count per row); zsv's
`--parser fast` is its branchless SIMD engine, so this is SIMD-vs-SIMD with the
extra variable being qwc's cross-core parallelism. Non-comma corpora pass the
delimiter to qwc as `--delim=<c>` and to zsv as `-O <c>`. Absolute numbers are
machine-specific -- the box is printed in the banner; record it with results.
"""
import argparse
import os
import platform
import shutil
import statistics
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "test-data")
SHAPES = ["unquoted", "sprinkled", "heavy", "ragged"]
DN = subprocess.DEVNULL

# Filename tags mirroring gen-csv.py, so we generate to (and look for) the same
# paths gen-csv.py would produce by hand.
DELIM_TAG = {",": "", "|": "-pipe", "\t": "-tab", ";": "-semi"}


def corpus_path(shape, delim=",", density=1):
    tag = DELIM_TAG.get(delim, f"-d{ord(delim)}")
    if shape == "ragged" and density > 1:
        tag += f"-x{density}"
    return os.path.join(DATA, f"csv-{shape}{tag}.csv")


def ensure_corpus(shape, size, seed, delim=",", density=1):
    path = corpus_path(shape, delim, density)
    if not os.path.exists(path):
        print(f"generating {path} ...", file=sys.stderr)
        cmd = [sys.executable, os.path.join(HERE, "gen-csv.py"),
               "--shape", shape, "--size", str(size), "--seed", str(seed),
               "--out", path]
        if delim != ",":
            cmd += ["--delim", delim]
        if shape == "ragged" and density > 1:
            cmd += ["--ragged-density", str(density)]
        subprocess.run(cmd, check=True)
    return path


def bench(cmd, runs):
    subprocess.run(cmd, stdout=DN, stderr=DN)  # warm the cache / discard output
    ts = []
    for _ in range(runs):
        t0 = time.perf_counter()
        subprocess.run(cmd, stdout=DN, stderr=DN)
        ts.append(time.perf_counter() - t0)
    return min(ts), statistics.median(ts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--qwc", default=os.path.join(os.getcwd(), "build", "qwc"))
    ap.add_argument("--zsv", default="zsv")
    ap.add_argument("--runs", type=int, default=7)
    ap.add_argument("--size", type=int, default=256 * 1024 * 1024)
    ap.add_argument("--seed", type=int, default=1234)
    ap.add_argument("--ragged-density", type=int, default=20,
                    help="scattered bad rows in the enumeration-section corpora "
                         "(sparse = the H1-favourable real-world shape)")
    args = ap.parse_args()

    if not (os.path.isfile(args.qwc) and os.access(args.qwc, os.X_OK)):
        sys.exit(f"qwc not found/executable at {args.qwc} "
                 f"(build it: cmake --build build --target qwc)")
    if shutil.which(args.zsv) is None:
        sys.exit(f"zsv not found on PATH ({args.zsv}); install it "
                 f"(e.g. brew install zsv) or pass --zsv")

    def qwc_cmd(path, *flags, delim=","):
        d = [f"--delim={delim}"] if delim != "," else []
        return [args.qwc, "--validate-csv", *d, *flags, path]

    def zsv_cmd(path, delim=","):
        # zsv's non-comma delimiter is -O/--other-delim; common opts precede the
        # filename. zsv row numbers run one lower than qwc's (it excludes the
        # header) but both name the same physical line -- irrelevant to timing.
        d = ["-O", delim] if delim != "," else []
        return [args.zsv, "check", "--parser", "fast", *d, path]

    # Record the box: absolute numbers are machine-specific (the README pins a
    # box per Finding), so self-document which one produced this run.
    print(f"qwc={args.qwc}  zsv={args.zsv}  runs={args.runs}  "
          f"size={args.size}  (median wall-clock)")
    print(f"box: {platform.platform()}  {platform.processor() or platform.machine()}\n")
    header = f"{'corpus':12} {'qwc':>12} {'zsv':>12} {'speedup':>9}"
    print(header)
    print("-" * len(header))
    for shape in SHAPES:
        path = ensure_corpus(shape, args.size, args.seed)
        flags = ("--fast",) if shape == "ragged" else ()
        _, q = bench(qwc_cmd(path, *flags), args.runs)
        _, z = bench(zsv_cmd(path), args.runs)
        label = "ragged --fast" if shape == "ragged" else shape
        print(f"{label:12} {q * 1000:9.1f} ms {z * 1000:9.1f} ms "
              f"{z / q:8.2f}x")

    # ------------------------------------------------------------------
    # Default-mode enumeration vs zsv: the real-world "many ragged rows"
    # case (TODO: "Beat zsv check in default --all/--first mode"). `zsv
    # check` enumerates anomalies single-threaded; qwc's default --all /
    # --first must re-read the file and scan it serially to name the rows
    # (the inspection tax), while --fast skips that. These cells are the
    # gap to close -- all/zsv < 1.0 means default mode loses to zsv.
    # (label, shape, delim, density)
    # ------------------------------------------------------------------
    enum_corpora = [
        ("ragged x{d} (comma)", "ragged", ",", args.ragged_density),
        ("ragged x{d} (pipe)",  "ragged", "|", args.ragged_density),
        ("ragged-everywhere",   "ragged-everywhere", ",", 1),
    ]
    print("\nDefault-mode enumeration vs zsv "
          "(--all/--first re-scan vs --fast fast path):\n")
    h2 = (f"{'corpus':22} {'--all':>9} {'--first':>9} {'--fast':>9} "
          f"{'zsv':>9} {'all/zsv':>8} {'fast/zsv':>9}")
    print(h2)
    print("-" * len(h2))
    for label, shape, delim, density in enum_corpora:
        path = ensure_corpus(shape, args.size, args.seed, delim, density)
        _, q_all = bench(qwc_cmd(path, "--all", delim=delim), args.runs)
        _, q_first = bench(qwc_cmd(path, "--first", delim=delim), args.runs)
        _, q_fast = bench(qwc_cmd(path, "--fast", delim=delim), args.runs)
        _, z = bench(zsv_cmd(path, delim=delim), args.runs)
        print(f"{label.format(d=density):22} "
              f"{q_all*1000:6.1f} ms {q_first*1000:6.1f} ms "
              f"{q_fast*1000:6.1f} ms {z*1000:6.1f} ms "
              f"{z/q_all:7.2f}x {z/q_fast:8.2f}x")
    print("\nall/zsv < 1.0x = qwc default mode LOSES to zsv (the inspection tax);"
          "\nfast/zsv = the headline once enumeration is parallelized (TODO H1-H3)."
          "\nNote: on ragged-everywhere qwc --all caps output at 1000 rows while"
          "\nzsv prints every anomaly, so that row's all/zsv flatters qwc.")


if __name__ == "__main__":
    main()
